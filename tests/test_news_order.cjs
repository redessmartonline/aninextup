const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.join(__dirname,'..');
const model=require('../assets/release-model.js');
const dates=require('../assets/news-dates.js');
const box={window:{}};vm.runInNewContext(fs.readFileSync(path.join(root,'assets/data.js'),'utf8'),box);
const data=box.window.ANINEXTUP_DATA;
const categories=new Set(['new-anime','returning-series','trailers-cast','release-news']);
const seen=new Set();
const input=[...data.anime,...data.guides].filter(x=>x.article&&categories.has(x.newsCategory)&&!seen.has(x.article)&&seen.add(x.article));
const ordered=model.sortNews(input,dates);
assert.equal(ordered[0].article,'articles/eleceed-anime-april-2027-release-date');
assert.equal(ordered.length,input.length);
const start=fs.readFileSync(path.join(root,'news.html'),'utf8').split('data-guides')[1];
const rendered=[...start.matchAll(/href="(articles\/[^"#]+)"/g)].map(m=>m[1]).slice(0,ordered.length);
assert.deepEqual(rendered,ordered.map(x=>x.article));
const example=[{article:'future-premiere',date:'2029-01-01'},{article:'new-news',date:'2026-01-01'},{article:'same-day-earlier'}];
const info={'future-premiere':{updated:'2026-10-01'},'new-news':{updated:'2026-10-21',publishedAt:20},'same-day-earlier':{updated:'2026-10-21',publishedAt:10}};
assert.deepEqual(model.sortNews(example,info).map(x=>x.article),['new-news','same-day-earlier','future-premiere']);
assert.deepEqual(example.map(x=>x.article),['future-premiere','new-news','same-day-earlier']);
console.log('PASS: News uses editorial recency, preserves every category, and matches server-rendered order.');
